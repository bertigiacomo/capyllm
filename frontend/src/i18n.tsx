const dictionaries: Record<Language, Translations> = { it, en };

interface I18nContextType {
  lang: Language;
  setLang: (lang: Language) => void;
  t: (key: string, params?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextType>({
  lang: 'it',
  setLang: () => {},
  t: (key: string) => key,
});

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLangState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('capy_lang');
      if (saved === 'it' || saved === 'en') return saved;
      return 'it';
    } catch {
      return 'it';
    }
  });

  const setLang = (newLang: Language) => {
    setLangState(newLang);
    try {
      localStorage.setItem('capy_lang', newLang);
      document.documentElement.lang = newLang;
    } catch {}
  };

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const t = (key: string, params?: Record<string, string | number>): string => {
    const dict = dictionaries[lang] || dictionaries.it;
    let template = dict[key] || dictionaries.it[key] || key;
    if (params) {
      for (const [pKey, pVal] of Object.entries(params)) {
        template = template.replace(new RegExp(`\\{${pKey}\\}`, 'g'), String(pVal));
      }
    }
    return template;
  };

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = () => useContext(I18nContext);
